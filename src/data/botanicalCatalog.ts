export interface CropRotationSuggestion {
  detectedCategory: string;
  nutrientClass: 'Starkzehrer' | 'Mittelzehrer' | 'Schwachzehrer' | 'Dauerkultur';
  year2Label: string;
  year2Options: Array<{ plantName: string; variety: string; nutrientNeed: string }>;
  year3Label: string;
  year3Options: Array<{ plantName: string; variety: string; nutrientNeed: string }>;
  year4Label: string;
  warningNote: string;
  explanation: string;
}

export function suggestCropRotation(
  currentPlantName: string,
  currentNutrientNeed?: string
): CropRotationSuggestion {
  const q = `${currentPlantName} ${currentNutrientNeed || ''}`.toLowerCase();

  const isPerennial =
    q.includes('erdbeer') ||
    q.includes('himbeer') ||
    q.includes('johannis') ||
    q.includes('stachelbeer') ||
    q.includes('apfel') ||
    q.includes('birne') ||
    q.includes('kirsch') ||
    q.includes('zwetsch') ||
    q.includes('dauerkultur');

  if (isPerennial) {
    return {
      detectedCategory: 'Dauerkultur / Mehrjährig',
      nutrientClass: 'Dauerkultur',
      year2Label: 'Bleibt stehen (Pflege & Kompostmulch)',
      year2Options: [
        { plantName: 'Knoblauch', variety: 'Germidour (Zwischensaat bei Erdbeeren)', nutrientNeed: 'Mittelzehrer' },
        { plantName: 'Spinat', variety: 'Matador (Unterpflanzung)', nutrientNeed: 'Schwachzehrer' },
      ],
      year3Label: 'Nach 3–4 Jahren bei Erdbeeren: Neues Beet wählen',
      year3Options: [
        { plantName: 'Buschbohnen', variety: 'Saxa', nutrientNeed: 'Schwachzehrer' },
        { plantName: 'Kopfsalat', variety: 'Maikönig', nutrientNeed: 'Mittelzehrer' },
      ],
      year4Label: 'Kompostauffrischung & Bodenruhe',
      warningNote: 'Erdbeeren am besten nach 3–4 Jahren auf ein frisches Beet umziehen.',
      explanation: 'Beeren und Obstgehölze bleiben mehrere Jahre am Platz — einfach im Frühjahr etwas Kompost auflegen.',
    };
  }

  const isHeavy =
    q.includes('starkzehrer') ||
    q.includes('tomate') ||
    q.includes('kartoffel') ||
    q.includes('kürbis') ||
    q.includes('zucchini') ||
    q.includes('kohl') ||
    q.includes('gurke') ||
    q.includes('paprika') ||
    q.includes('chili');

  const isMedium =
    !isHeavy &&
    (q.includes('mittelzehrer') ||
      q.includes('möhre') ||
      q.includes('karotte') ||
      q.includes('rote bete') ||
      q.includes('zwiebel') ||
      q.includes('knoblauch') ||
      q.includes('salat') ||
      q.includes('kohlrabi') ||
      q.includes('petersilie'));

  const isCabbage = q.includes('kohl') || q.includes('brokkoli') || q.includes('radies');
  const isNightshade = q.includes('tomate') || q.includes('kartoffel') || q.includes('paprika') || q.includes('aubergine');

  if (isHeavy) {
    return {
      detectedCategory: isCabbage
        ? 'Starkzehrer (Kohlgewächs)'
        : isNightshade
        ? 'Starkzehrer (Nachtschatten)'
        : 'Starkzehrer',
      nutrientClass: 'Starkzehrer',
      year2Label: 'Jahr 2: Mittelzehrer (nutzen Restnährstoffe ohne frischen Mist)',
      year2Options: [
        { plantName: 'Möhren', variety: 'Nantes 2', nutrientNeed: 'Mittelzehrer' },
        { plantName: 'Rote Bete', variety: 'Rote Kugel 2', nutrientNeed: 'Mittelzehrer' },
        { plantName: 'Kopfsalat', variety: 'Maikönig', nutrientNeed: 'Mittelzehrer' },
      ],
      year3Label: 'Jahr 3: Schwachzehrer (Boden erholt sich)',
      year3Options: [
        { plantName: 'Buschbohnen', variety: 'Saxa', nutrientNeed: 'Schwachzehrer' },
        { plantName: 'Zuckererbsen', variety: 'Norli', nutrientNeed: 'Schwachzehrer' },
        { plantName: 'Feldsalat', variety: 'Verte de Cambrai', nutrientNeed: 'Schwachzehrer' },
      ],
      year4Label: 'Jahr 4: Gründüngung (z.B. Phacelia) oder wieder Starkzehrer mit Kompost',
      warningNote: isCabbage
        ? 'Wichtig bei Kohl: Möglichst 4 Jahre keinen Kohl (auch keine Radieschen/Rettich) auf genau dieses Beet.'
        : isNightshade
        ? 'Tipp: Tomaten und Kartoffeln nicht direkt nacheinander aufs selbe Freilandbeet (Krautfäule-Vorbeugung).'
        : 'Im Jahr nach Starkzehrern keinen frischen Mist geben — eine Portion Kompost reicht locker.',
      explanation: 'Nach hungrigen Pflanzen (Tomate, Zucchini, Kohl, Kartoffel) folgen im nächsten Jahr entspannte Mittelzehrer und danach Stickstoffsammler wie Bohnen oder Erbsen.',
    };
  }

  if (isMedium) {
    return {
      detectedCategory: 'Mittelzehrer',
      nutrientClass: 'Mittelzehrer',
      year2Label: 'Jahr 2: Schwachzehrer / Stickstoffsammler',
      year2Options: [
        { plantName: 'Buschbohnen', variety: 'Saxa', nutrientNeed: 'Schwachzehrer' },
        { plantName: 'Zuckererbsen', variety: 'Norli', nutrientNeed: 'Schwachzehrer' },
        { plantName: 'Radieschen', variety: 'Saxa 2', nutrientNeed: 'Schwachzehrer' },
      ],
      year3Label: 'Jahr 3: Frischer Kompost + Starkzehrer',
      year3Options: [
        { plantName: 'Zucchini', variety: 'Black Beauty', nutrientNeed: 'Starkzehrer' },
        { plantName: 'Tomaten', variety: 'Harzfeuer', nutrientNeed: 'Starkzehrer' },
        { plantName: 'Kartoffeln', variety: 'Laura', nutrientNeed: 'Starkzehrer' },
      ],
      year4Label: 'Jahr 4: Wieder Mittelzehrer',
      warningNote: 'Möhren & Petersilie (beides Doldenblütler) besser nicht direkt nacheinander anbauen.',
      explanation: 'Auf Mittelzehrer folgen ganz entspannt Erbsen, Bohnen oder Feldsalat — danach darf das Beet wieder mit Kompost für Starkzehrer gestärkt werden.',
    };
  }

  return {
    detectedCategory: 'Schwachzehrer / Boden-Aufbauer',
    nutrientClass: 'Schwachzehrer',
    year2Label: 'Jahr 2: Starkzehrer (profitieren vom Stickstoff der Bohnen/Erbsen!)',
    year2Options: [
      { plantName: 'Tomaten', variety: 'Harzfeuer', nutrientNeed: 'Starkzehrer' },
      { plantName: 'Zucchini', variety: 'Black Beauty', nutrientNeed: 'Starkzehrer' },
      { plantName: 'Grünkohl', variety: 'Lerchenzungen', nutrientNeed: 'Starkzehrer' },
    ],
    year3Label: 'Jahr 3: Mittelzehrer',
    year3Options: [
      { plantName: 'Möhren', variety: 'Nantes 2', nutrientNeed: 'Mittelzehrer' },
      { plantName: 'Rote Bete', variety: 'Rote Kugel 2', nutrientNeed: 'Mittelzehrer' },
      { plantName: 'Winterknoblauch', variety: 'Germidour', nutrientNeed: 'Mittelzehrer' },
    ],
    year4Label: 'Jahr 4: Zurück zu Schwachzehrern / Kräutern',
    warningNote: 'Bohnen und Erbsen hinterlassen natürlichen Stickstoff im Boden — super Start für Starkzehrer.',
    explanation: 'Nach Schwachzehrern oder Leguminosen (Bohnen, Erbsen) darf im nächsten Jahr ruhig etwas Hungriges mit einer Schaufel Kompost folgen.',
  };
}

